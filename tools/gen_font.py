def column_bytes(rows):
    out = []
    for c in range(5):
        b = 0
        for r in range(7):
            if rows[r][c] == '#':
                b |= 1 << r
        out.append(b)
    return out


def main(path):
    first, last = 32, 126
    missing = [chr(c) for c in range(first, last + 1) if chr(c) not in GLYPHS]
    if missing:
        raise SystemExit("missing glyphs: %r" % missing)

    lines = [
        "/* generated by tools/gen_font.py -- do not edit by hand.",
        " * 5x7 bitmap font, printable ASCII 32..126, column-major: one byte per column,",
        " * bit 0 = top row. Hand-written as pictures in the generator so a wrong pixel is",
        " * visible in the source rather than buried in hex. */",
        '#include "fm_ui.h"',
        "",
        "/* %d glyphs, 5 bytes each */" % (last - first + 1),
        "const uint8_t fm_ui_font[FM_UI_FONT_GLYPHS][FM_UI_FONT_W] = {",
    ]
    for code in range(first, last + 1):
        ch = chr(code)
        cols = column_bytes(GLYPHS[ch])
        label = ch if ch not in ('\\', "'") else {'\\': 'backslash', "'": "apostrophe"}[ch]
        lines.append("    {%s},  /* %3d %s */" % (", ".join("0x%02x" % v for v in cols), code, label))
    lines.append("};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d glyphs)" % (path, last - first + 1))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "components/fmengine/src/fm_ui_font.c")
